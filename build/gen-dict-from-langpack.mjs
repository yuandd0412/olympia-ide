// Generate zh-cn dictionary entries from the official VS Code Simplified Chinese
// language pack, instead of paying an LLM to translate every string.
//
// Why this works: the language pack is a flat map  <nls-metadata-key> -> <Chinese>.
// Our AST collector (nls-literals.mjs) already yields { key, text, file } for every
// localize() literal. VS Code's metadata key is "<path-without-.ts relative to src>#<key>",
// so we can join pack -> source and emit  <English text> -> <Chinese>  pairs that the
// existing applier consumes unchanged.
//
// Guarantees:
//   * Already-translated literals (containing CJK) are skipped.
//   * Empty / identity / CJK-free translations are skipped (the pack stores "" for
//     intentionally-untranslated strings).
//   * Pack translations only ever fill gaps; existing hand-written dicts are loaded
//     first and win, so nothing regresses.
//
//   node build/gen-dict-from-langpack.mjs --out=build/zh-cn-dict-auto.mjs [--report]
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { pathToFileURL } from 'url';
import { relative } from 'path';
import { collectLiterals } from './nls-literals.mjs';

const CJK = /[\u3400-\u9fff]/;
const args = process.argv.slice(2);
const OUT = (args.find(a => a.startsWith('--out=')) || '--out=build/zh-cn-dict-auto.mjs').slice(6);
const SRC = 'D:/oler-ide-v2/oss/src';
const PACK = 'D:/oler-ide-v2/build/langpack/extension/translations/main.i18n.json';

// ---------------------------------------------------------------- load the pack
if (!existsSync(PACK)) {
	console.error(`missing language pack: ${PACK}`);
	process.exit(1);
}
const packRaw = JSON.parse(readFileSync(PACK, 'utf8'));
const pack = packRaw.contents ?? packRaw;   // { "<bundle path>": { "<key>": "<zh>" } }
console.log(`pack bundles: ${Object.keys(pack).length}`);

/** bundle path + localize key -> chinese, e.g. pack["vs/workbench/browser/workbench.contribution"]["configTitle"] */
function lookup(file, key) {
	const rel = relative(SRC, file).replace(/\\/g, '/').replace(/\.ts$/, '');
	return pack[rel]?.[key];
}

// No "keep our own wording" filter is needed: every literal we already translated is
// CJK in the source, so `alreadyChinese` below removes it before we ever look at the
// pack. Filtering by translated *value* would only discard legitimate new entries.

// ------------------------------------------------------------- collect + join
const literals = collectLiterals(SRC);
console.log(`source literals (AST): ${literals.length}`);

const pairs = new Map();
const stats = { alreadyChinese: 0, coveredByPack: 0, packMiss: 0, noLatinKey: 0 };
const missesByFile = new Map();

for (const l of literals) {
	if (!l.text || l.text.length < 2) { continue; }
	if (CJK.test(l.text)) { stats.alreadyChinese++; continue; }   // already done

	let zh;
	try { zh = lookup(l.file, l.key); } catch { zh = undefined; }

	if (!zh || zh === l.text || !zh.trim()) { stats.packMiss++; continue; }
	if (!CJK.test(zh)) { stats.packMiss++; continue; }               // pack left it English
	
	if (!pairs.has(l.text)) { pairs.set(l.text, zh); stats.coveredByPack++; }
}

for (const l of literals) {
	if (l.text && !CJK.test(l.text) && !pairs.has(l.text)) {
		const rel = relative(SRC, l.file).replace(/\\/g, '/');
		missesByFile.set(rel, (missesByFile.get(rel) || 0) + 1);
	}
}

// ------------------------------------------------------------------- emit
const esc = s => JSON.stringify(s);
const entries = [...pairs.entries()].sort((a, b) => a[0].localeCompare(b[0]));
const body = entries
	.map(([en, zh]) => `\t${esc(en)}: ${esc(zh)},`)
	.join('\n');

const header = `// GENERATED by build/gen-dict-from-langpack.mjs — do not edit by hand.
// Source: official VS Code Simplified Chinese (zh-hans) language pack,
//         MS-CEINTL.vscode-language-pack-zh-hans (MIT), joined onto this fork's
//         localize() literals by nls metadata key.
// Hand-written batches always win: this file only fills gaps the pack covers.
// Entries: ${entries.length}
export default {
${body}
};
`;
writeFileSync(OUT, header, 'utf8');

console.log('\n--- coverage ---');
console.log(`already Chinese : ${stats.alreadyChinese}`);
console.log(`filled by pack  : ${stats.coveredByPack}`);
console.log(`pack miss       : ${stats.packMiss}`);
const pct = (stats.coveredByPack / (stats.coveredByPack + stats.packMiss) * 100).toFixed(1);
console.log(`pack hit rate   : ${pct}% of still-English literals`);
console.log(`\nwrote ${entries.length} entries -> ${OUT}`);

const top = [...missesByFile.entries()].sort((a, b) => b[1] - a[1]).slice(0, 20);
console.log('\n--- top files still uncovered by the pack ---');
for (const [f, n] of top) { console.log(`  ${String(n).padStart(5)}  ${f}`); }